    @Test func exportDirectoryBatchCreatesMultipleFiles() throws {
        let path = Self.testDataPath
        try #require(FileManager.default.fileExists(atPath: path))

        // Count .dmp files in test data directory
        let dmpFiles = try FileManager.default.contentsOfDirectory(atPath: path)
            .filter { $0.hasSuffix(".dmp") }
        try #require(!dmpFiles.isEmpty)

        let tmpDir = FileManager.default.temporaryDirectory
            .appendingPathComponent("cli-test-batch-\(UUID().uuidString)")
        defer { try? FileManager.default.removeItem(at: tmpDir) }

        let result = try Self.runCLI("export", "-f", "text", "-o", tmpDir.path, path)

        #expect(result.exitCode == 0)
        let outputFiles = try FileManager.default.contentsOfDirectory(atPath: tmpDir.path)
            .filter { $0.hasSuffix(".txt") }
        #expect(outputFiles.count == dmpFiles.count)
    }

